export function levelBase(table: readonly number[], level: number): number {
  if (table.length === 0) return 0;
  if (!Number.isFinite(level)) return table[table.length - 1];
  const index = Math.min(table.length, Math.max(1, Math.round(level))) - 1;
  return table[index];
}
